# -*- coding: utf-8 -*-
"""
The 'init' command: commented templates of conductor.toml and llm.toml.

Templates are rendered from the schema (llm_conductor/schema.py), so every key the
loader accepts appears in them with its description and default.
"""
import json
import math
import os
from typing import Any, List, Optional, Tuple

from llm_conductor.core.io import FileOperations, safe_write_file
from llm_conductor.exceptions import ConfigValidationError, FileOperationError
from llm_conductor.interfaces import FileOperationsProtocol
from llm_conductor.schema import CONDUCTOR_SCHEMA, LLM_SCHEMA, FileSchema, Setting

_LITERAL_DELIMITER = "'''"
_DEL = "\x7f"


def format_toml_value(value: Any) -> str:
    """
    Render a scalar or a list as a TOML value.

    Strings become basic (double-quoted) strings: JSON escapes are a subset
    of TOML ones, and DEL, which JSON leaves raw but TOML forbids, is
    escaped separately.

    Args:
        value: bool, int, float, str, or a list/tuple of those.

    Returns:
        The TOML representation.

    Raises:
        TypeError: For any other type (tables are rendered by the caller).
    """
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        if math.isnan(value):
            return "nan"
        if math.isinf(value):
            return "inf" if value > 0 else "-inf"
        return repr(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False).replace(_DEL, "\\u007f")
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(format_toml_value(item) for item in value) + "]"
    raise TypeError(f"Cannot render {type(value).__name__} as a TOML value")


def format_toml_multiline(value: str) -> str:
    """
    Render a string as a multi-line literal, kept byte for byte without escaping.

    Falls back to a basic string when a literal cannot hold the text
    (it contains ''' or control characters other than newline and tab, or
    ends with a quote that would merge with the closing delimiter).

    Args:
        value: The string.

    Returns:
        The TOML representation.
    """
    has_control = any((ch < " " or ch == _DEL) and ch not in "\n\t" for ch in value)
    if _LITERAL_DELIMITER in value or has_control or value.endswith("'"):
        return format_toml_value(value)
    # The newline right after the opening delimiter is trimmed by TOML parsers.
    return f"{_LITERAL_DELIMITER}\n{value}{_LITERAL_DELIMITER}"


class TomlTemplateRenderer:
    """Renders a FileSchema as a commented TOML file filled with the defaults."""

    def __init__(self, schema: FileSchema):
        """
        Args:
            schema: Schema of the file to render.
        """
        self._schema = schema

    def render(self) -> str:
        """
        Build the template text.

        Returns:
            A TOML document that parses back to the schema defaults.
        """
        lines: List[str] = self._comment(self._schema.header)
        lines += self._comment("Generated by `llm-conductor init`. Absent keys take the defaults below; "
                               "unknown keys are an error.")
        for section in self._schema.sections:
            lines.append("")
            lines += self._comment(section.description)
            lines.append(f"[{section.name}]")
            for setting in section.settings:
                lines += self._render_setting(setting)
        return "\n".join(lines) + "\n"

    def _render_setting(self, setting: Setting) -> List[str]:
        """Comment line(s) and the key line of one setting."""
        value = setting.init_value
        if setting.multiline:
            return self._comment(setting.description) + [
                f"{setting.key} = {format_toml_multiline(value)}"]
        rendered = format_toml_value(value)
        # Comment shows the absent-key default; the line may use template_default.
        default_note = format_toml_value(setting.default)
        return self._comment(f"{setting.description} Default: {default_note}") + [
            f"{setting.key} = {rendered}"]

    @staticmethod
    def _comment(text: str) -> List[str]:
        """Turn text into '# '-prefixed lines."""
        return [f"# {line}" if line else "#" for line in text.split("\n")]


def create_config_files(conductor_path: str, llm_path: str,
                        file_ops: Optional[FileOperationsProtocol] = None) -> None:
    """
    Write fresh conductor.toml and llm.toml templates.

    Existing files are never overwritten: a configured profile may hold
    hand-tuned prompts and keys.

    Args:
        conductor_path: Destination of conductor.toml.
        llm_path: Destination of llm.toml.
        file_ops: File operations for writing; default FileOperations.

    Raises:
        ConfigValidationError: If either file already exists.
        FileOperationError: If a file cannot be written.
    """
    targets: Tuple[Tuple[str, FileSchema], ...] = ((conductor_path, CONDUCTOR_SCHEMA), (llm_path, LLM_SCHEMA))
    existing = [path for path, _ in targets if os.path.exists(path)]
    if existing:
        raise ConfigValidationError(
            f"Refusing to overwrite existing configuration: {', '.join(existing)}. "
            f"Remove or rename the file(s) to generate fresh templates.")

    writer = file_ops or FileOperations()
    for path, schema in targets:
        text = TomlTemplateRenderer(schema).render()
        if not safe_write_file(path, text, f"{schema.file_name} template", writer):
            raise FileOperationError(f"Failed to write {path}")
        print(f"Created {path}")

    print("For OpenAI-compatible APIs (OpenAI, DeepSeek, OpenRouter), edit llm.toml:")
    print("  - set type = \"openai\" and url in [translation.api] / [verification.api]")
    print("  - set key_env to the environment variable holding the key (or key to the key itself)")
